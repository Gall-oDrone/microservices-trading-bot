var updateEpisodes = flag.Bool("update-episodes", false, "rewrite episode_paths_gen.go from the committed Yahoo CSVs")

// yahooDir holds the committed index histories the known paths come from.
var yahooDir = filepath.Join("..", "..", "..", "docs", "backtest-readiness", "evidence-2026-10-10", "data")

// episodeCSVs are the index files, by symbol.
var episodeCSVs = map[string]string{
	"^NDX":  "ndx_yahoo_daily.csv",
	"^GSPC": "gspc_yahoo_daily.csv",
}

func readIndexCloses(t *testing.T, f string) []varmodel.Close {
	t.Helper()
	rows, err := yahoodaily.ReadCSV(filepath.Join(yahooDir, f))
	if err != nil {
		t.Fatal(err)
	}
	cs := make([]varmodel.Close, len(rows))
	for i, r := range rows {
		d, err := time.Parse("2006-01-02", r.Date)
		if err != nil {
			t.Fatal(err)
		}
		cs[i] = varmodel.Close{Date: d, Price: r.Close}
	}
	return cs
}

func buildKnown(t *testing.T) map[string]map[string][]varmodel.PathPoint {
	out := map[string]map[string][]varmodel.PathPoint{}
	for sym, f := range episodeCSVs {
		out[sym] = IndexEpisodePaths(readIndexCloses(t, f))
	}
	return out
}

func renderKnown(known map[string]map[string][]varmodel.PathPoint) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by go test -run TestKnownIndexEpisodePathsMatchCSVs -update-episodes; DO NOT EDIT.\n\n")
	b.WriteString("package cfdrisk\n\n")
	b.WriteString("import \"bitso-trading-platform/shared/pkg/varmodel\"\n\n")
	b.WriteString("// KnownIndexEpisodePaths are the indices' paths through IndexEpisodes,\n")
	b.WriteString("// computed from the committed Yahoo daily closes\n")
	b.WriteString("// (docs/backtest-readiness/evidence-2026-10-10/data). A nil path means the\n")
	b.WriteString("// index has no close in the window. The past does not change, so the risk\n")
	b.WriteString("// report can run from these without the CSVs on disk.\n")
	b.WriteString("var KnownIndexEpisodePaths = map[string]map[string][]varmodel.PathPoint{\n")
	syms := make([]string, 0, len(known))
	for k := range known {
		syms = append(syms, k)
	}
	sort.Strings(syms)
	for _, sym := range syms {
		fmt.Fprintf(&b, "%q: {\n", sym)
		for _, e := range IndexEpisodes {
			p := known[sym][e.ID]
			if p == nil {
				fmt.Fprintf(&b, "%q: nil,\n", e.ID)
				continue
			}
			fmt.Fprintf(&b, "%q: {\n", e.ID)
			for _, pt := range p {
				fmt.Fprintf(&b, "{Date: date(%q), Cum: %v},\n", pt.Date.Format("2006-01-02"), pt.Cum)
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	return src
}

// TestKnownIndexEpisodePathsMatchCSVs fails when episode_paths_gen.go no
// longer matches the committed CSVs or IndexEpisodes (e.g. an episode was
// added). Regenerate with:
// go test ./pkg/cfdrisk -run TestKnownIndexEpisodePathsMatchCSVs -update-episodes
func TestKnownIndexEpisodePathsMatchCSVs(t *testing.T) {
	known := buildKnown(t)
	if *updateEpisodes {
		if err := os.WriteFile("episode_paths_gen.go", renderKnown(known), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if !reflect.DeepEqual(known, KnownIndexEpisodePaths) {
		t.Fatal("episode_paths_gen.go is stale; run: go test ./pkg/cfdrisk -run TestKnownIndexEpisodePathsMatchCSVs -update-episodes")
	}
	for sym, eps := range KnownIndexEpisodePaths {
		if len(eps) != len(IndexEpisodes) {
			t.Errorf("%s: %d episodes known, want all %d", sym, len(eps), len(IndexEpisodes))
		}
	}
}

// The episodes on the committed index closes: every window has a path on
// both indices, is complete (one close per NYSE trading day), its trough is
// at the window's end (the dates were chosen as last calm close -> trough;
// ^NDX bottomed one session before ^GSPC in March 2020, 0.13 pp lower, and
// the replay takes the worst common day anyway), and the troughs are the
// documented ones.
func TestIndexEpisodesOnYahooHistory(t *testing.T) {
	want := map[string]map[string]float64{
		"^NDX": {
			"2008-09-lehman": -0.406, "2010-05-flash-crash": -0.033, "2011-08-downgrade": -0.152,
			"2015-08-china": -0.121, "2018-02-volmageddon": -0.102, "2018-12-q4": -0.165,
			"2020-03-covid": -0.280, "2022-bear": -0.346, "2025-04-tariffs": -0.127,
		},
		"^GSPC": {
			"2008-09-lehman": -0.401, "2010-05-flash-crash": -0.032, "2011-08-downgrade": -0.168,
			"2015-08-china": -0.112, "2018-02-volmageddon": -0.102, "2018-12-q4": -0.157,
			"2020-03-covid": -0.339, "2022-bear": -0.254, "2025-04-tariffs": -0.121,
		},
	}
	for sym, f := range episodeCSVs {
		cs := readIndexCloses(t, f)
		for _, e := range IndexEpisodes {
			p, ok := IndexEpisodePath(cs, e)
			if !ok {
				t.Errorf("%s %s: no path", sym, e.ID)
				continue
			}
			if n := mktcal.TradingDaysBetween(e.Base, e.End); len(p) != n {
				t.Errorf("%s %s: %d closes in the window, %d trading days", sym, e.ID, len(p), n)
			}
			tr := varmodel.Trough(p)
			if last := p[len(p)-1].Cum; last-tr > 0.002 {
				t.Errorf("%s %s: trough %.4f is not at the window's end (%.4f)", sym, e.ID, tr, last)
			}
			if w := want[sym][e.ID]; math.Abs(tr-w) > 0.001 {
				t.Errorf("%s %s: trough %.4f, want %.3f", sym, e.ID, tr, w)
			}
		}
	}
}
