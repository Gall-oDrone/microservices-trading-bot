#!/usr/bin/env bash
# Generate the k8s PrometheusRule copies (kube-prometheus-stack) of the plain-Prometheus
# rule files, so the two never drift:
#
#   monitoring/prometheus/rules/trading-risk-alerts.yml -> k8s/monitoring/trading-risk-rules.yaml
#   monitoring/prometheus/rules/trading-slo-rules.yml   -> k8s/monitoring/trading-slo-rules.yaml
#
#   scripts/sync-prometheus-rules.sh          # rewrite the k8s files
#   scripts/sync-prometheus-rules.sh --check  # exit 1 if any is out of date (CI)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"

# name|source|destination
pairs=(
  "trading-risk-alerts|monitoring/prometheus/rules/trading-risk-alerts.yml|k8s/monitoring/trading-risk-rules.yaml"
  "trading-slo-rules|monitoring/prometheus/rules/trading-slo-rules.yml|k8s/monitoring/trading-slo-rules.yaml"
)

render() { # name src
  local name="$1" src="$2"
  cat <<EOF
# GENERATED by scripts/sync-prometheus-rules.sh from
# ${src#"$root/"}. Do not edit by hand.
apiVersion: monitoring.coreos.com/v1
kind: PrometheusRule
metadata:
  name: ${name}
  namespace: monitoring
  labels:
    release: kube-prometheus-stack
    app: kube-prometheus-stack
spec:
EOF
  # Everything from "groups:" on, indented under spec.
  sed -n '/^groups:/,$p' "$src" | sed 's/^/  /; s/^  $//'
}

rc=0
for p in "${pairs[@]}"; do
  IFS='|' read -r name src dst <<<"$p"
  src="$root/$src"; dst="$root/$dst"
  if [[ "${1:-}" == "--check" ]]; then
    if ! diff -u "$dst" <(render "$name" "$src"); then
      echo "${dst#"$root/"} is out of date: run scripts/sync-prometheus-rules.sh" >&2
      rc=1
    else
      echo "${dst#"$root/"} is in sync"
    fi
  else
    render "$name" "$src" >"$dst"
    echo "wrote ${dst#"$root/"}"
  fi
done
exit $rc
